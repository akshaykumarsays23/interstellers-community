/**
 * generate-welcome-images.mjs
 *
 * Scans public/welcomepage/ and writes a TypeScript module containing the list
 * of all supported image filenames. This script runs as a prebuild step so
 * the deployed Vercel build always has an up-to-date image list without
 * requiring any manual code changes when new images are added.
 *
 * Supported extensions: .png  .jpg  .jpeg  .webp  .avif
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const WELCOME_DIR = path.join(ROOT, 'public', 'welcomepage');
const OUT_FILE = path.join(ROOT, 'src', 'lib', 'welcomeImages.ts');

const SUPPORTED = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif']);

let images = [];

if (fs.existsSync(WELCOME_DIR)) {
  images = fs
    .readdirSync(WELCOME_DIR)
    .filter((f) => SUPPORTED.has(path.extname(f).toLowerCase()))
    .map((f) => `/welcomepage/${f}`);
} else {
  console.warn('[generate-welcome-images] WARNING: public/welcomepage/ directory not found.');
}

const content = `// AUTO-GENERATED by scripts/generate-welcome-images.mjs
// Do NOT edit this file manually — run \`node scripts/generate-welcome-images.mjs\`
// or let the prebuild step regenerate it automatically.
//
// Generated at: ${new Date().toISOString()}
// Image count: ${images.length}

export const WELCOME_PAGE_IMAGES: string[] = ${JSON.stringify(images, null, 2)};
`;

fs.writeFileSync(OUT_FILE, content, 'utf8');
console.log(`[generate-welcome-images] ✅ Written ${images.length} images to src/lib/welcomeImages.ts`);
images.forEach((img) => console.log(`  • ${img}`));
